#!/usr/bin/env python3
"""Generates the committed short-lived self-signed localhost certificate (#332).

Apple's trust evaluation rejects a TLS server certificate whose validity period is longer than
398 days (errSecCertificateValidityPeriodTooLong, -67901) before it checks the anchor, so a
long-lived certificate issued today cannot show "no trust anchor" on iOS or macOS. The two
self-signed-without-anchor tests use this certificate instead: same identity (CN=localhost, SAN
localhost, 127.0.0.1, ::1, serverAuth, RSA 2048), valid for 397 days from the day before
generation.

Unity's Mono cannot create certificates at runtime (#151), so the PKCS#12 is committed as base64
with SHA1/3DES (the only PBE Mono reads). Test material only, never trusted by anything.
TestShortLivedLocalhostCertificateTests fails 30 days before NotAfter: regenerate then with

    python3 'Tools~/test-certs/gen_short_lived_localhost_cert.py' \
        > Tests/Runtime/Transport/Tls/TestShortLivedLocalhostCertificate.cs

Requires the `cryptography` package (38 or later).
"""
import base64
import datetime as dt
import ipaddress
import textwrap

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.serialization import pkcs12
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

PASSWORD = "turbohttp-test"
VALIDITY_DAYS = 397  # Apple's limit is 398 days; one day of margin for how the period is counted.


def build(not_before=None, not_after=None, authority_key_id=False):
    """A new key and self-signed localhost certificate; without dates, the short-lived window."""
    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, "localhost")])
    if not_before is None:
        today = dt.datetime.now(dt.timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0, tzinfo=None)
        not_before = today - dt.timedelta(days=1)  # tolerate a device clock a day behind
        not_after = not_before + dt.timedelta(days=VALIDITY_DAYS)
    cert = (x509.CertificateBuilder()
            .subject_name(name)
            .issuer_name(name)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(not_before)
            .not_valid_after(not_after)
            .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
            .add_extension(x509.KeyUsage(digital_signature=True, key_encipherment=True, content_commitment=False,
                                         data_encipherment=False, key_agreement=False, key_cert_sign=False,
                                         crl_sign=False, encipher_only=False, decipher_only=False), critical=True)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
            .add_extension(x509.SubjectAlternativeName([
                x509.DNSName("localhost"),
                x509.IPAddress(ipaddress.ip_address("127.0.0.1")),
                x509.IPAddress(ipaddress.ip_address("::1")),
            ]), critical=False)
            .add_extension(x509.SubjectKeyIdentifier.from_public_key(key.public_key()), critical=False))
    if authority_key_id:
        cert = cert.add_extension(x509.AuthorityKeyIdentifier.from_issuer_public_key(key.public_key()),
                                  critical=False)
    cert = cert.sign(key, hashes.SHA256())
    encryption = (serialization.PrivateFormat.PKCS12.encryption_builder()
                  .kdf_rounds(2048)
                  .key_cert_algorithm(pkcs12.PBES.PBESv1SHA1And3KeyTripleDESCBC)
                  .hmac_hash(hashes.SHA1())
                  .build(PASSWORD.encode("ascii")))
    pfx = pkcs12.serialize_key_and_certificates(b"localhost", key, cert, None, encryption)
    return cert, pfx


def pfx_lines(pfx):
    """The PKCS#12 as a C# string concatenation, 96 base64 characters per line."""
    b64 = base64.b64encode(pfx).decode("ascii")
    return " +\n".join(f'            "{line}"' for line in textwrap.wrap(b64, 96))


def emit(cert, pfx):
    body = pfx_lines(pfx)
    nb = getattr(cert, "not_valid_before_utc", cert.not_valid_before).strftime("%Y-%m-%d")
    na = getattr(cert, "not_valid_after_utc", cert.not_valid_after).strftime("%Y-%m-%d")
    return f"""// <auto-generated>
// Generated by Tools~/test-certs/gen_short_lived_localhost_cert.py (#332); do not edit by hand.
// </auto-generated>
using System;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;

namespace TurboHTTP.Tests.Transport.Tls
{{
    /// <summary>
    /// Self-signed <c>CN=localhost</c> test identity with a validity period Apple accepts (397 days,
    /// {nb} to {na}), for the cases that expect "no trust anchor" (#332). Apple rejects a
    /// long-lived certificate issued today for its validity period (-67901) before the anchor check.
    /// Unlike <see cref="TestLocalhostCertificate"/>, loading this one registers no test trust anchor.
    /// </summary>
    /// <remarks>
    /// Test material, not a secret: SAN localhost, 127.0.0.1, ::1, serverAuth, RSA 2048, PKCS#12 with
    /// SHA1/3DES so Mono can read it. TestShortLivedLocalhostCertificateTests fails 30 days before
    /// NotAfter; regenerate with
    /// <c>python3 'Tools~/test-certs/gen_short_lived_localhost_cert.py' &gt; Tests/Runtime/Transport/Tls/TestShortLivedLocalhostCertificate.cs</c>.
    /// </remarks>
    internal static class TestShortLivedLocalhostCertificate
    {{
        /// <summary>Validity period in days the generator writes; Apple's limit is 398.</summary>
        internal const int ValidityDays = {VALIDITY_DAYS};

        private const string Password = "{PASSWORD}";

        private const string PfxBase64 =
{body};

        /// <summary>A new instance (caller disposes), or null if this runtime cannot load PKCS#12.</summary>
        internal static X509Certificate2 TryLoad()
        {{
            try
            {{
                return new X509Certificate2(
                    Convert.FromBase64String(PfxBase64),
                    Password,
                    X509KeyStorageFlags.Exportable);
            }}
            catch (CryptographicException)
            {{
                return null;
            }}
            catch (NotSupportedException)
            {{
                // Also covers PlatformNotSupportedException.
                return null;
            }}
        }}
    }}
}}
"""


if __name__ == "__main__":
    print(emit(*build()), end="")
