#!/usr/bin/env python3
"""Generates the committed self-signed localhost certificate the loopback TLS tests anchor (#332).

Apple's trust evaluation caps the validity period of a TLS server certificate issued on or after
2019-07-01 (as its NotBefore says) at 825 days, and rejects a longer one with
errSecCertificateValidityPeriodTooLong (-67901) even when the test registers it as an anchor
(macOS hands the anchors to SecTrust). This certificate predates that rule: valid 2001-01-01 to
2126-01-01, like the chain-validation fixtures (gen_chain_validation_certs.py) that SecTrust accepts.
So it never expires under the suite and needs no scheduled regeneration. Same identity as
gen_short_lived_localhost_cert.py plus an authority key identifier, as the certificate it replaced:
CN=localhost, SAN localhost, 127.0.0.1, ::1, serverAuth, RSA 2048, PKCS#12 with SHA1/3DES (the only
PBE Mono reads). TestLocalhostCertificateTests guards the window.

    python3 'Tools~/test-certs/gen_localhost_cert.py' \
        > Tests/Runtime/Transport/Tls/TestLocalhostCertificate.cs

Requires the `cryptography` package (38 or later).
"""
import datetime as dt

from gen_short_lived_localhost_cert import PASSWORD, build, pfx_lines

NOT_BEFORE = dt.datetime(2001, 1, 1)
NOT_AFTER = dt.datetime(2126, 1, 1)


def emit(pfx):
    body = pfx_lines(pfx)
    nb = NOT_BEFORE.strftime("%Y-%m-%d")
    na = NOT_AFTER.strftime("%Y-%m-%d")
    return f"""// <auto-generated>
// Generated by Tools~/test-certs/gen_localhost_cert.py (#332); do not edit by hand.
// </auto-generated>
using System;
using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using TurboHTTP.Transport.Tls;

namespace TurboHTTP.Tests.Transport.Tls
{{
    /// <summary>
    /// A committed, test-only TLS server identity for loopback tests. Unity's Mono cannot create
    /// certificates at runtime (<c>CertificateRequest</c> is unavailable), which made every
    /// real-TLS test skip in the Editor (#151).
    /// </summary>
    /// <remarks>
    /// Test material, not a secret: self-signed <c>CN=localhost</c> (SAN localhost, 127.0.0.1, ::1),
    /// RSA 2048, serverAuth, valid {nb} to {na}, PKCS#12 with SHA1/3DES so Mono can read
    /// it. Nothing trusts it: platform <c>SslStream</c> rejects it (the fail-closed tests rely on that).
    /// The BouncyCastle provider validates the chain (#33), so <see cref="TryLoad"/> registers this
    /// certificate as a test-only trust anchor (<c>ServerCertificateVerifier.AddTestTrustAnchor</c>)
    /// for every loopback test that loads it; production code never registers an anchor, and the
    /// chain-validation tests show the same certificate is rejected without it. NotBefore predates
    /// 2019-07-01 so Apple's 825-day cap on certificates issued since then does not apply (#332:
    /// a 100-year certificate issued in 2026 failed every anchored test on macOS with -67901);
    /// TestLocalhostCertificateTests guards that. Regenerate with
    /// <c>python3 'Tools~/test-certs/gen_localhost_cert.py' &gt; Tests/Runtime/Transport/Tls/TestLocalhostCertificate.cs</c>.
    /// </remarks>
    internal static class TestLocalhostCertificate
    {{
        private const string Password = "{PASSWORD}";

        private const string PfxBase64 =
{body};

        /// <summary>
        /// A new instance (caller disposes), or null if this runtime cannot load PKCS#12. Also trusts
        /// the certificate as a BouncyCastle test anchor (idempotent, process-wide).
        /// </summary>
        internal static X509Certificate2 TryLoad()
        {{
            try
            {{
                var certificate = new X509Certificate2(
                    Convert.FromBase64String(PfxBase64),
                    Password,
                    X509KeyStorageFlags.Exportable);
                ServerCertificateVerifier.AddTestTrustAnchor(certificate.RawData);
                return certificate;
            }}
            catch (CryptographicException)
            {{
                return null;
            }}
            catch (NotSupportedException)
            {{
                // Also covers PlatformNotSupportedException.
                return null;
            }}
        }}
    }}
}}
"""


if __name__ == "__main__":
    _, pfx = build(NOT_BEFORE, NOT_AFTER, authority_key_id=True)
    print(emit(pfx), end="")
